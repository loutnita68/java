    private void btnrigisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrigisterActionPerformed
        String userName = userNameField.getText().trim();
        String phoneNumber = phoneNumberField.getText().trim();
        String password = passwordField.getText().trim();
        if (userName.isEmpty() || phoneNumber.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
        } else {
            try {
                java.sql.Connection con = dbConnection.getConnection();

                
                String checkSql = "SELECT * FROM users WHERE username = ?";
                java.sql.PreparedStatement checkPs = con.prepareStatement(checkSql);
                checkPs.setString(1, userName);
                java.sql.ResultSet rs = checkPs.executeQuery();

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Username already taken! Try another one.");
                } else {
                    
                    String sql = "INSERT INTO users (username, phone, password) VALUES (?, ?, ?)";
                    java.sql.PreparedStatement ps = con.prepareStatement(sql);
                    ps.setString(1, userName);
                    ps.setString(2, phoneNumber);
                    ps.setString(3, password);

                    ps.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Welcome to the Coffee Shop, " + userName + "!");
                    
                    Main mainPage = new Main(); 
                    mainPage.setVisible(true);   

                    this.dispose();

                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnrigisterActionPerformed

